create or replace function public.community_username(value text, fallback_id uuid)
returns text
language sql
immutable
as $$
  select left(
    trim(both '_' from regexp_replace(lower(coalesce(nullif(value, ''), 'uye')), '[^a-z0-9_]+', '_', 'g'))
    || '_' || left(replace(fallback_id::text, '-', ''), 6),
    30
  );
$$;

create or replace function public.community_handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  desired_name text;
begin
  desired_name := coalesce(nullif(new.raw_user_meta_data->>'display_name', ''), split_part(new.email, '@', 1), 'Yeni Üye');
  insert into public.community_profiles (id, display_name, username)
  values (
    new.id,
    left(desired_name, 60),
    public.community_username(coalesce(new.raw_user_meta_data->>'username', split_part(new.email, '@', 1)), new.id)
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_community on auth.users;
create trigger on_auth_user_created_community
after insert on auth.users
for each row execute function public.community_handle_new_user();

-- Mevcut kullanıcılar için profil oluştur. En eski hesap site yöneticisidir.
with ranked_users as (
  select
    id,
    email,
    raw_user_meta_data,
    raw_app_meta_data,
    row_number() over (order by created_at asc) as account_order
  from auth.users
)
insert into public.community_profiles (id, display_name, username, role)
select
  id,
  left(coalesce(nullif(raw_user_meta_data->>'display_name', ''), split_part(email, '@', 1), 'Yeni Üye'), 60),
  public.community_username(coalesce(raw_user_meta_data->>'username', split_part(email, '@', 1)), id),
  case when raw_app_meta_data->>'site_role' = 'admin' or account_order = 1 then 'admin' else 'member' end
from ranked_users
on conflict (id) do update
set role = case
  when excluded.role = 'admin' then 'admin'
  else public.community_profiles.role
end;

create or replace function public.is_community_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.community_profiles
    where id = auth.uid() and role = 'admin' and status = 'active'
  );
$$;

create or replace function public.community_guard_post()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  profile_record public.community_profiles%rowtype;
begin
  if tg_op = 'INSERT' then
    if new.user_id is null then
      return new;
    end if;
    select * into profile_record from public.community_profiles where id = auth.uid();
    if profile_record.id is null or profile_record.status <> 'active' or new.user_id <> auth.uid() then
      raise exception 'Bu hesap paylaşım yapamaz.';
    end if;
    new.author_name := profile_record.display_name;
    new.author_username := coalesce(profile_record.username, 'uye');
    new.is_featured := false;
    if public.is_community_admin() then
      new.status := 'published';
    elsif exists (select 1 from public.community_posts where user_id = auth.uid() and status = 'published') then
      new.status := 'published';
    else
      new.status := 'pending';
    end if;
    return new;
  end if;

  if not public.is_community_admin() then
    new.user_id := old.user_id;
    new.author_name := old.author_name;
    new.author_username := old.author_username;
    new.status := old.status;
    new.is_featured := old.is_featured;
  end if;
  return new;
end;
$$;

