create extension if not exists pgcrypto;

create table if not exists public.community_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Yeni Üye' check (char_length(display_name) between 2 and 60),
  username text unique check (username is null or username ~ '^[a-z0-9_]{3,30}$'),
  bio text not null default '' check (char_length(bio) <= 240),
  avatar_url text not null default '',
  role text not null default 'member' check (role in ('member', 'admin')),
  status text not null default 'active' check (status in ('active', 'suspended')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.community_posts (
  id bigint generated by default as identity primary key,
  user_id uuid references public.community_profiles(id) on delete cascade,
  author_name text not null default '',
  author_username text not null default '',
  content text not null check (char_length(content) between 20 and 1500),
  topic text not null default 'Gündelik Hayat' check (char_length(topic) between 2 and 40),
  status text not null default 'pending' check (status in ('pending', 'published', 'rejected', 'removed')),
  is_featured boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.community_likes (
  post_id bigint not null references public.community_posts(id) on delete cascade,
  user_id uuid not null references public.community_profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (post_id, user_id)
);

create table if not exists public.community_comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.community_posts(id) on delete cascade,
  user_id uuid not null references public.community_profiles(id) on delete cascade,
  content text not null check (char_length(content) between 2 and 500),
  status text not null default 'published' check (status in ('published', 'removed')),
  created_at timestamptz not null default now()
);

create table if not exists public.community_reports (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.community_posts(id) on delete cascade,
  user_id uuid not null references public.community_profiles(id) on delete cascade,
  reason text not null check (char_length(reason) between 3 and 300),
  status text not null default 'open' check (status in ('open', 'reviewed', 'closed')),
  created_at timestamptz not null default now(),
  unique (post_id, user_id)
);

create index if not exists community_posts_feed_idx on public.community_posts (status, is_featured desc, created_at desc);
create index if not exists community_posts_user_idx on public.community_posts (user_id, created_at desc);
create index if not exists community_comments_post_idx on public.community_comments (post_id, created_at asc);
create index if not exists community_reports_status_idx on public.community_reports (status, created_at desc);

